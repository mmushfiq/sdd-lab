-- Seasonal rates per room type, and the saved rate of each night of a reservation.
CREATE TABLE seasonal_rate
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_type_id BIGINT         NOT NULL REFERENCES room_type (id),
    name         VARCHAR(50)    NOT NULL,
    first_night  DATE           NOT NULL,
    last_night   DATE           NOT NULL,
    nightly_rate DECIMAL(10, 2) NOT NULL CHECK (nightly_rate > 0),
    CHECK (last_night >= first_night)
);

CREATE INDEX seasonal_rate_room_type_ix ON seasonal_rate (room_type_id, first_night);

CREATE TABLE reservation_night
(
    reservation_id BIGINT         NOT NULL REFERENCES reservation (id),
    night_date     DATE           NOT NULL,
    nightly_rate   DECIMAL(10, 2) NOT NULL CHECK (nightly_rate > 0),
    PRIMARY KEY (reservation_id, night_date)
);

-- Existing reservations: one night row per night at the reservation's single rate.
INSERT INTO reservation_night (reservation_id, night_date, nightly_rate)
SELECT r.id, DATEADD(DAY, n.X, r.arrival_date), r.nightly_rate
FROM reservation r
         JOIN SYSTEM_RANGE(0, 3660) n ON n.X < DATEDIFF(DAY, r.arrival_date, r.departure_date);
