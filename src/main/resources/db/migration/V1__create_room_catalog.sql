create table room_type
(
    id           bigint generated by default as identity primary key,
    name         varchar(50)    not null,
    -- H2 has no expression index, so case-insensitive uniqueness uses a generated column
    name_lower   varchar(50) generated always as (lower(name)),
    capacity     int            not null check (capacity between 1 and 10),
    nightly_rate decimal(10, 2) not null check (nightly_rate > 0),
    constraint room_type_name_uk unique (name_lower)
);

create table room
(
    id             bigint generated by default as identity primary key,
    number         varchar(10) not null,
    room_type_id   bigint      not null,
    out_of_service boolean     not null default false,
    constraint room_number_uk unique (number),
    constraint room_room_type_fk foreign key (room_type_id) references room_type (id)
);

