create table reservation
(
    id               bigint generated by default as identity primary key,
    booking_number   char(8)        not null,
    room_id          bigint         not null,
    arrival          date           not null,
    departure        date           not null,
    number_of_guests int            not null check (number_of_guests >= 1),
    guest_name       varchar(100)   not null,
    guest_email      varchar(254)   not null,
    guest_phone      varchar(30)    not null,
    total_price      decimal(10, 2) not null,
    status           varchar(10)    not null check (status in ('CONFIRMED', 'CANCELLED')),
    anonymized       boolean        not null default false,
    created_at       timestamp      not null default current_timestamp,
    constraint reservation_booking_number_uk unique (booking_number),
    constraint reservation_room_fk foreign key (room_id) references room (id),
    constraint reservation_period_ck check (departure > arrival)
);

create index reservation_room_arrival_ix on reservation (room_id, arrival);
